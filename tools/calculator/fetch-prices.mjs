#!/usr/bin/env node
/* ───────────────────────────────────────────────────────────────
   tools/calculator/fetch-prices.mjs — the pricing sync.

   The calculator's model table used to be curated by hand, which meant
   a row either had a price someone typed or a dash that stayed a dash.
   This script makes the dashes a pipeline state instead: it reads the
   model ids straight out of public/calculator/data.js, looks each one
   up in two public, keyless registries, and regenerates
   public/calculator/prices.auto.js.

     1. LiteLLM's model_prices_and_context_window.json  (primary —
        per-token input/output prices plus real context windows)
     2. OpenRouter's /api/v1/models                     (fallback —
        catches ids LiteLLM carries only under provider mirrors, like
        xAI's groks, or not at all, like Mistral's pinned ids)

   Precedence lives in data.js, not here: a curated price (platform
   billing table, dated list price, labeled placeholder) always wins —
   this script only fills gaps and context windows. Run it by hand or
   let .github/workflows/refresh-prices.yml open a PR when the numbers
   moved. The generated file is committed, so the deployed site never
   fetches anything at runtime.

   Node >= 18, no dependencies. Writes only when content changed.
   ─────────────────────────────────────────────────────────────── */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const DATA = join(ROOT, "public", "calculator", "data.js");
const OUT = join(ROOT, "public", "calculator", "prices.auto.js");

const LITELLM_URL =
  "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json";
const OPENROUTER_URL = "https://openrouter.ai/api/v1/models";

/* data.js model providers → OpenRouter's slug space */
const OPENROUTER_SLUG = {
  openai: "openai", anthropic: "anthropic", xai: "x-ai", google: "google",
  deepseek: "deepseek", mistral: "mistralai", algolia: null,
};
/* LiteLLM mirrors some providers under prefixes instead of their home ids */
const LITELLM_PREFIXES = (id) => [`xai/${id}`, `oci/xai.${id}`, `azure_ai/${id}`];

const fetched = process.argv[2] || new Date().toISOString().slice(0, 10);

const dataText = readFileSync(DATA, "utf8");
const modelsBlock = dataText.slice(dataText.indexOf("models: ["), dataText.indexOf("providers: ["));
const ids = [...modelsBlock.matchAll(/id: "([^"]+)"/g)].map((m) => m[1]);
const providers = [...modelsBlock.matchAll(/provider: "([^"]+)"/g)].map((m) => m[1]);
if (ids.length !== providers.length) {
  throw new Error(`parsed ${ids.length} ids but ${providers.length} providers — data.js layout changed?`);
}
const MODELS = ids.map((id, i) => ({ id, provider: providers[i] }));

async function getJson(url) {
  const res = await fetch(url, { headers: { "User-Agent": "agent-studio-demos-pricing-sync" } });
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return res.json();
}

const [litellm, openrouter] = await Promise.all([getJson(LITELLM_URL), getJson(OPENROUTER_URL)]);

/* OpenRouter's ids carry ":batch"/":floor" variants; skip them */
const orIndex = new Map();
for (const m of openrouter.data || []) {
  if (m.id.includes(":")) continue;
  orIndex.set(m.id, m);
}

function fromLitellm(id) {
  const e = litellm[id] ?? LITELLM_PREFIXES(id).map((k) => litellm[k]).find(Boolean);
  if (!e || e.input_cost_per_token == null || e.output_cost_per_token == null) return null;
  return {
    inPerMTok: e.input_cost_per_token * 1e6,
    outPerMTok: e.output_cost_per_token * 1e6,
    contextWindow: e.max_input_tokens ?? null,
    via: "litellm",
  };
}

function fromOpenrouter(id, provider) {
  const slug = OPENROUTER_SLUG[provider];
  if (!slug) return null;
  const m = orIndex.get(`${slug}/${id}`);
  const p = m?.pricing;
  if (!p || p.prompt == null || p.completion == null) return null;
  return {
    inPerMTok: Number(p.prompt) * 1e6,
    outPerMTok: Number(p.completion) * 1e6,
    contextWindow: m.context_length ?? null,
    via: "openrouter",
  };
}

const prices = {};
const unresolved = [];
for (const { id, provider } of MODELS) {
  const hit = fromLitellm(id) ?? fromOpenrouter(id, provider);
  if (hit) prices[id] = hit; else unresolved.push(id);
}

/* Round to a readable precision: LiteLLM carries float artifacts like
   0.09999999999999999 that would otherwise ship as-is. */
for (const p of Object.values(prices)) {
  p.inPerMTok = Number(p.inPerMTok.toPrecision(3));
  p.outPerMTok = Number(p.outPerMTok.toPrecision(3));
}

const payload = {
  fetched,
  sourceLabel: "LiteLLM model registry + OpenRouter (whichever priced the row first)",
  prices,
};

const header = `/* GENERATED by tools/calculator/fetch-prices.mjs on ${fetched} — do not edit by hand.
   Source: ${payload.sourceLabel}. Curated prices in data.js always win; this file
   only fills rows data.js leaves unpriced and context windows it leaves unknown.
   Refresh: node tools/calculator/fetch-prices.mjs (CI does it weekly). */\n`;
const body = `${header}window.CALC_AUTO_PRICES = ${JSON.stringify(payload, null, 2)};\n`;

let previous = "";
try { previous = readFileSync(OUT, "utf8"); } catch { /* first run */ }
if (previous === body) {
  console.log(`prices.auto.js unchanged (${Object.keys(prices).length} priced, ${unresolved.length} unresolved)`);
} else {
  writeFileSync(OUT, body);
  console.log(`wrote prices.auto.js: ${Object.keys(prices).length} priced, ${unresolved.length} unresolved`);
}
if (unresolved.length) console.log(`unresolved: ${unresolved.join(", ")}`);
