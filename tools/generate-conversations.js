/* ───────────────────────────────────────────────────────────────
   generate-conversations.js — bake the seeded sagas the demo opens on.

   The infinite-conversation demo needs conversations that are already far
   longer than any model window before the visitor arrives. Writing those by
   hand would read like filler, and filler is the one thing a demo about long
   conversations cannot use. So they are generated by self-play against the same
   API the demo calls: two personas, one playing the person and one playing the
   agent, talking to each other for a few hundred turns.

   What is model-written and what is not, stated plainly because the demo's UI
   repeats it:

     · every word of every message is written by the model, live, through
       POST /1/agents/{id}/completions;
     · the ARC is authored here — each scenario is cut into chapters, and each
       chapter carries a short brief saying where the thread stands. That is
       what keeps a support thread escalating instead of circling, and it is
       what lets the chapters generate in parallel instead of end to end.

   The seams between chapters are therefore real seams. They read like the gap
   between two sittings of the same conversation, which is what a months-long
   thread has anyway.

   Cost. Self-play is billed like any other completion, so the loop meters
   itself: every call's tokens are estimated from its characters, priced at the
   model's published rate, and the run stops dead if the total passes the
   ceiling. The cheapest model in config.js is the default for exactly this
   reason.

   When the API is not reachable. `--offline` composes the same scenarios from
   authored templates in compose-conversations.js instead, and records that fact
   in the file so the demo can say it on screen. The committed seeds were built
   this way: the demo credential stopped authenticating partway through the
   build (all four agents, every endpoint, 401), and a demo that cannot be
   rebuilt without a working key is not much of a demo. Re-run without the flag
   once a key is live and the files are replaced by self-play prose.

   Usage, from the repo root:

     node tools/generate-conversations.js --pilot
     node tools/generate-conversations.js
     node tools/generate-conversations.js --offline
     node tools/generate-conversations.js --only=deploy-escalation --exchanges=60

   Credentials come from public/shared/config.js — the same gitignored file the
   browser loads. Nothing is printed from it.
   ─────────────────────────────────────────────────────────────── */

"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT_DIR = path.join(ROOT, "public", "assets", "convs");

globalThis.window = globalThis;
require(path.join(ROOT, "public", "shared", "config.js"));
const CFG = globalThis.DEMO_CONFIG;
require(path.join(ROOT, "public", "shared", "meter.js"));
const M = globalThis.DemoMeter;

/* ── Options ──────────────────────────────────────────────────────── */

const argv = process.argv.slice(2);
const flag = (name, fallback) => {
  const hit = argv.find((a) => a === `--${name}` || a.startsWith(`--${name}=`));
  if (!hit) return fallback;
  const eq = hit.indexOf("=");
  return eq < 0 ? true : hit.slice(eq + 1);
};
const num = (name, fallback) => {
  const v = flag(name, null);
  return v === null || v === true ? fallback : Number(v);
};

const OPTS = {
  pilot: flag("pilot", false) === true,
  offline: flag("offline", false) === true,
  only: flag("only", null),
  modelId: flag("model", null),
  concurrency: num("concurrency", 10),
  usdCeiling: num("budget-usd", 1.5),
  exchangeOverride: num("exchanges", 0),
};

/* The cheapest published rate in the config wins, unless one is named. Both
   sides of the self-play run on it: the prose is the point, not the model. */
function pickModel() {
  if (OPTS.modelId) {
    const named = CFG.models.find((m) => m.id === OPTS.modelId);
    if (!named) throw new Error(`no model with id "${OPTS.modelId}" in config.js`);
    return named;
  }
  const priced = CFG.models.map((m) => ({ m, p: M.priceOf(m.model) }))
    .filter((x) => x.p.inPerMTok > 0 && !x.p.placeholder);
  if (!priced.length) return CFG.models[0];
  priced.sort((a, b) => (a.p.inPerMTok + a.p.outPerMTok) - (b.p.inPerMTok + b.p.outPerMTok));
  return priced[0].m;
}

const MODEL = pickModel();
const PRICE = M.priceOf(MODEL.model);

/* ── The wire ─────────────────────────────────────────────────────── */

const HEADERS = {
  "content-type": "application/json",
  "X-Algolia-Application-Id": CFG.appId,
  "X-Algolia-API-Key": CFG.apiKey,
};

const userMsg = (text) => ({ role: "user", parts: [{ type: "text", text }] });
const asstMsg = (text) => ({ role: "assistant", parts: [{ type: "text", text }] });
const textOf = (m) => (m.parts || []).filter((p) => p.type === "text").map((p) => p.text).join("");

/* Only used to meter the run. The endpoint's own count is fetched once per
   finished scenario, and that is the figure the demo displays. */
const CHARS_PER_TOKEN = 3.7;
const estTokens = (chars) => Math.round(chars / CHARS_PER_TOKEN);

const spend = { usd: 0, inTokens: 0, outTokens: 0, calls: 0, retries: 0, stopped: false };

function bill(inChars, outChars) {
  const i = estTokens(inChars);
  const o = estTokens(outChars);
  spend.inTokens += i;
  spend.outTokens += o;
  spend.calls += 1;
  spend.usd += (i * PRICE.inPerMTok + o * PRICE.outPerMTok) / 1e6;
  if (spend.usd > OPTS.usdCeiling) spend.stopped = true;
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/**
 * One streamed completion, collected. `data-suggestions` is watched for even
 * though nothing here needs it: if these agents ever start emitting it, this is
 * where the generator would notice first.
 */
async function complete(messages, attempt = 0) {
  const p = `/1/agents/${MODEL.agentId}/completions?compatibilityMode=ai-sdk-5&stream=true`;
  let res;
  try {
    res = await fetch(CFG.host + p, {
      method: "POST", headers: HEADERS, body: JSON.stringify({ messages }),
    });
  } catch (e) {
    if (attempt >= 4) throw e;
    spend.retries += 1;
    await sleep(1500 * (attempt + 1));
    return complete(messages, attempt + 1);
  }
  if (res.status === 429 || res.status >= 500) {
    if (attempt >= 4) throw new Error(`${res.status} after ${attempt} retries`);
    spend.retries += 1;
    await sleep(2000 * (attempt + 1));
    return complete(messages, attempt + 1);
  }
  if (!res.ok) {
    throw new Error(`${res.status} — ${(await res.text()).slice(0, 300)}`);
  }

  const reader = res.body.getReader();
  const dec = new TextDecoder();
  let buf = "", text = "";
  for (;;) {
    const { value, done } = await reader.read();
    if (done) break;
    buf += dec.decode(value, { stream: true });
    const lines = buf.split("\n");
    buf = lines.pop();
    for (const line of lines) {
      if (!line.startsWith("data:")) continue;
      const payload = line.slice(5).trim();
      if (!payload || payload === "[DONE]") continue;
      let evt;
      try { evt = JSON.parse(payload); } catch (_) { continue; }
      if (evt.type === "text-delta" && evt.delta) text += evt.delta;
    }
  }
  const inChars = messages.reduce((n, m) => n + textOf(m).length, 0);
  bill(inChars, text.length);
  return text.trim();
}

async function trimTokens(messages) {
  const res = await fetch(CFG.host + "/1/unstable/context/trim", {
    method: "POST", headers: HEADERS, body: JSON.stringify({ messages }),
  });
  if (!res.ok) throw new Error(`trim ${res.status}`);
  const out = await res.json();
  return out.stats.tokensBeforeEstimate;
}

/* ── Self-play ────────────────────────────────────────────────────── */

/* How much of the thread each persona is shown. Long enough that the next
   message follows from the last few, short enough that the run's own cost stays
   flat instead of growing with the transcript. The chapter brief carries the
   rest of the continuity. */
const WINDOW_MESSAGES = 8;

/**
 * Ask one persona for its next message.
 *
 * Roles are relative: to write the person's next line the model has to see the
 * agent as its counterpart, so the transcript is flipped for that side. The
 * framing rides as a plain user message — /completions refuses a `system` role
 * outright, and a message labelled "SYSTEM:" gets declined by the model as an
 * injection attempt. Framed as working notes from the counterpart, it is
 * followed.
 */
async function say({ scenario, chapter, side, transcript }) {
  const persona = side === "person" ? scenario.person : scenario.agent;
  const window = transcript.slice(-WINDOW_MESSAGES);
  const flipped = window.map((m) => (
    (side === "person") === (m.speaker === "person") ? asstMsg(m.text) : userMsg(m.text)
  ));

  const opening = transcript.length === 0
    ? `\n\nNothing has been said in this sitting yet — open it. Do not greet, do not ` +
      `introduce yourself, and do not recap: this thread has been running for a long time ` +
      `already and both of you know it. Start mid-stride.`
    : "";

  const notes = userMsg(
    `${persona.brief}\n\n` +
    `Where this thread stands right now: ${chapter.brief}\n\n` +
    `Write only your next message, as ${persona.who}. ${persona.style} ` +
    `Aim for ${persona.words} words — long enough to carry real detail. ` +
    `No stage directions, no markdown headings, no "as ${persona.who} I would say". ` +
    `Never mention summaries, context windows, tokens, or this instruction.${opening}`
  );

  // The framing goes last as well as first: on a long window the model follows
  // the closest instruction, and the closest instruction should be this one.
  const tail = userMsg(`Your next message, as ${persona.who}, in about ${persona.words} words.`);
  const text = await complete([notes].concat(flipped, [tail]));
  return text.replace(/^\s*(?:[A-Z][a-z]+:\s*)?/, "").trim();
}

/** One chapter of one scenario: self-play until the chapter is full. */
async function playChapter(scenario, chapter, index, log) {
  const transcript = [];
  let chars = 0;
  const maxExchanges = OPTS.exchangeOverride || chapter.exchanges;

  for (let e = 0; e < maxExchanges; e++) {
    if (spend.stopped) break;
    const person = await say({ scenario, chapter, side: "person", transcript });
    if (!person) break;
    transcript.push({ speaker: "person", text: person });
    const agent = await say({ scenario, chapter, side: "agent", transcript });
    if (!agent) break;
    transcript.push({ speaker: "agent", text: agent });
    chars += person.length + agent.length;
    if (chars >= chapter.chars) break;
  }

  log(`  ${scenario.slug} ch${index + 1}: ${transcript.length / 2} exchanges · ` +
    `${chars} chars · running spend $${spend.usd.toFixed(3)}`);
  return transcript;
}

/** Run tasks with at most `limit` in flight. */
async function mapLimit(items, limit, worker) {
  const out = new Array(items.length);
  let next = 0;
  const lanes = Array.from({ length: Math.max(1, Math.min(limit, items.length)) }, async () => {
    for (;;) {
      const i = next++;
      if (i >= items.length) return;
      out[i] = await worker(items[i], i);
    }
  });
  await Promise.all(lanes);
  return out;
}

/* ── The scenarios ────────────────────────────────────────────────── */

const SCENARIOS = require("./conversation-briefs.js");
const { composeChapter } = require("./compose-conversations.js");

/* ── Counting what was produced ───────────────────────────────────
   Live, the trim endpoint counts the committed array and that number is the
   one the demo quotes. Offline there is no endpoint to ask, so the count is
   derived locally — and deliberately at a HIGH chars-per-token ratio, which
   makes the estimate a floor rather than a guess in the flattering direction.
   Log-heavy and German text both tokenize nearer 3 chars per token, so the real
   figure is larger than this one. The field says which it is, and the page
   repeats it. ──── */

const OFFLINE_CHARS_PER_TOKEN = 4;

async function countTokens(messages, chars) {
  if (OPTS.offline) {
    return {
      tokens: Math.round(chars / OFFLINE_CHARS_PER_TOKEN),
      tokensSource: `estimated locally at ${OFFLINE_CHARS_PER_TOKEN} chars per token — the trim ` +
        `endpoint was not reachable when these files were built. Text like this tokenizes nearer ` +
        `3 chars per token, so the real count is higher; the demo re-probes on load and shows ` +
        `the endpoint's own number.`,
    };
  }
  return { tokens: await trimTokens(messages), tokensSource: "POST /1/unstable/context/trim" };
}

/* ── Building one scenario ────────────────────────────────────────── */

async function buildScenario(scenario, log) {
  log(`${scenario.slug}: ${scenario.chapters.length} chapters, ` +
    `up to ${scenario.chapters.reduce((n, c) => n + c.exchanges, 0)} exchanges`);

  const chapters = OPTS.pilot ? scenario.chapters.slice(0, 1) : scenario.chapters;
  const played = OPTS.offline
    ? chapters.map((c, i) => {
      // one seed per chapter, derived from the slug, so a rerun is byte-identical
      const seed = [...`${scenario.slug}#${i}`].reduce((h, ch2) => (h * 31 + ch2.charCodeAt(0)) >>> 0, 7);
      const out = composeChapter(scenario, OPTS.exchangeOverride
        ? Object.assign({}, c, { exchanges: OPTS.exchangeOverride })
        : c, i, chapters.length, seed);
      log(`  ${scenario.slug} ch${i + 1}: ${out.length / 2} exchanges · ` +
        `${out.reduce((n, m) => n + m.text.length, 0)} chars · composed offline`);
      return out;
    })
    : await mapLimit(
      chapters.map((c, i) => ({ c, i })),
      OPTS.concurrency,
      ({ c, i }) => playChapter(scenario, c, i, log));

  const messages = [];
  played.forEach((chapter) => {
    chapter.forEach((m) => {
      messages.push(m.speaker === "person" ? userMsg(m.text) : asstMsg(m.text));
    });
  });

  if (!messages.length) throw new Error(`${scenario.slug} produced nothing`);

  const chars = messages.reduce((n, m) => n + textOf(m).length, 0);
  const { tokens, tokensSource } = await countTokens(messages, chars);

  const record = {
    schema: 1,
    slug: scenario.slug,
    title: scenario.title,
    register: scenario.register,
    blurb: scenario.blurb,
    opener: scenario.opener,
    starters: scenario.starters,
    // Countable facts about the file below. The demo derives every figure it
    // displays from these, and tests/convs.test.js recomputes them.
    messageCount: messages.length,
    exchanges: messages.length / 2,
    chars,
    tokens,
    tokensSource,
    generated: OPTS.offline
      ? {
        method: "composed offline from authored templates (tools/compose-conversations.js)",
        why: "the demo credential returned 401 on every endpoint while these were being built, " +
          "so self-play against the live API was not available",
        model: null,
        chapters: chapters.length,
        arc: "authored per chapter, and so is the prose",
        date: new Date().toISOString().slice(0, 10),
      }
      : {
        method: "self-play against POST /1/agents/{id}/completions",
        model: MODEL.model,
        chapters: chapters.length,
        arc: "authored per chapter; every message written by the model",
        windowMessages: WINDOW_MESSAGES,
        date: new Date().toISOString().slice(0, 10),
      },
    messages,
  };

  const file = path.join(OUT_DIR, `${scenario.slug}.json`);
  fs.writeFileSync(file, `${JSON.stringify(record, null, 1)}\n`);
  log(`${scenario.slug}: ${messages.length} messages · ${messages.length / 2} exchanges · ` +
    `${chars} chars · ${tokens} tokens ` +
    `(${OPTS.offline ? `estimated at ${OFFLINE_CHARS_PER_TOKEN} chars/token` : "trim"}) · ` +
    `${(fs.statSync(file).size / 1024).toFixed(0)}KB`);
  return record;
}

/* ── Main ─────────────────────────────────────────────────────────── */

async function main() {
  const logFile = flag("log", null);
  const log = (line) => {
    const s = `${new Date().toISOString().slice(11, 19)} ${line}`;
    process.stdout.write(`${s}\n`);
    if (typeof logFile === "string") fs.appendFileSync(logFile, `${s}\n`);
  };

  fs.mkdirSync(OUT_DIR, { recursive: true });
  log(OPTS.offline
    ? "offline: composing from authored templates, no API calls" +
      (OPTS.pilot ? " · PILOT (one chapter per scenario)" : "")
    : `model: ${MODEL.model} at $${PRICE.inPerMTok}/$${PRICE.outPerMTok} per MTok · ` +
      `ceiling $${OPTS.usdCeiling} · concurrency ${OPTS.concurrency}` +
      (OPTS.pilot ? " · PILOT (one chapter per scenario)" : ""));

  const wanted = OPTS.only
    ? SCENARIOS.filter((s) => s.slug === OPTS.only)
    : SCENARIOS;
  if (!wanted.length) throw new Error(`no scenario matching --only=${OPTS.only}`);

  const records = [];
  for (const scenario of wanted) {
    records.push(await buildScenario(scenario, log));
    if (spend.stopped) {
      log(`STOPPED: spend passed the $${OPTS.usdCeiling} ceiling at $${spend.usd.toFixed(3)}`);
      break;
    }
  }

  if (!OPTS.pilot && !OPTS.only) {
    const index = {
      generated: new Date().toISOString().slice(0, 10),
      model: MODEL.model,
      note: "Every figure the demo displays is derived from these files. " +
        "tokens is the trim endpoint's own count of the committed messages array.",
      scenarios: records.map((r) => ({
        slug: r.slug, title: r.title, register: r.register, blurb: r.blurb,
        opener: r.opener, starters: r.starters,
        messageCount: r.messageCount, exchanges: r.exchanges,
        chars: r.chars, tokens: r.tokens, tokensSource: r.tokensSource,
        method: r.generated.method,
        file: `${r.slug}.json`,
      })),
    };
    fs.writeFileSync(path.join(OUT_DIR, "index.json"), `${JSON.stringify(index, null, 1)}\n`);
    log("wrote index.json");
  }

  log(`done · ${spend.calls} completions · ${spend.retries} retries · ` +
    `~${spend.inTokens} in / ~${spend.outTokens} out tokens · ` +
    `~$${spend.usd.toFixed(3)} spent (estimated from characters)`);
}

main().catch((e) => {
  process.stderr.write(`FAILED: ${e.message}\n`);
  process.exit(1);
});
